export const DICTIONARY = Object.freeze(Object.fromEntries(ENTRIES.map((e) => [e.id, e])));

/** An entry's text in the given language, English when the language is missing. */
export const entryText = (e, field, lang = 'en') => e?.[field]?.[lang] || e?.[field]?.en || '';

/** On-screen label → entry id (term in English, plus each entry's aliases). */
const BY_LABEL = (() => {
  const m = new Map();
  ENTRIES.forEach((e) => [e.term.en, ...(e.aliases || [])].forEach((l) => { if (!m.has(l)) m.set(l, e.id); }));
  return m;
})();
/** The entry id for a label as the page writes it, or null. */
export const termIdForLabel = (label) => {
  if (typeof label !== 'string') return null;
  const l = label.trim();
  // A label with a live part after " — " ("Conversion (3m) — company rate (n=5)") is its first part.
  return BY_LABEL.get(l) || BY_LABEL.get(l.split(' — ')[0].trim()) || null;
};
